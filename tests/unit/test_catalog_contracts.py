"""Frontend Reference Manual & Pixel Assist Catalog Contract Verification.

Dynamically parses web/src/modules/catalog.ts and verifies that all documented
snippets, command candidates, and generated templates adhere to normative
compiler and runtime specifications with 100% ABI compliance.
"""

import re
from pathlib import Path
import pytest
from macro import Macro
from mock_hid import MockHID
from runtime import Runtime


@pytest.fixture
def macro():
    rt = Runtime()
    rt.register_ns("sys", {
        "free": ([], "int", lambda: 10000),
    })
    rt.register_signal("net.msg")
    rt.register_ns("net", {
        "send": (["str"], "int", lambda tag: 1),
    })
    rt.register_ns("img", {
        "snap": (["rect"], "snap", lambda x, y, w, h: 1),
        "at": (["snap", "point"], "color", lambda s, x, y: 0),
        "diff": (["snap", "snap", "int"], "int", lambda a, b, tol: 0),
        "watch": (["str", "point", "span"], "int", lambda name, x, y, interval, duration: 1),
        "unwatch": (["str"], "int", lambda name: 1),
    })
    return Macro(MockHID(), rt)


def test_catalog_manual_snippets_dynamically(macro):
    """Dynamically parses web/src/modules/catalog.ts and verifies that every single
    manual snippet compiles cleanly without errors."""
    catalog_path = Path("web/src/modules/catalog.ts")
    assert catalog_path.exists(), "web/src/modules/catalog.ts must exist"
    content = catalog_path.read_text(encoding="utf-8")

    item_pattern = re.compile(
        r"""item\s*\(\s*(?:"(?:\\.|[^"\\])*"|`[^`]*`)\s*,\s*(?:"(?:\\.|[^"\\])*"|`[^`]*`)\s*,\s*(?:"(?:\\.|[^"\\])*"|`[^`]*`)\s*,\s*((?:"(?:\\.|[^"\\])*"|`[^`]*`))""",
        re.DOTALL,
    )
    matches = item_pattern.findall(content)
    assert len(matches) > 50, f"Expected > 50 manual snippets, found {len(matches)}"

    for raw in matches:
        if raw.startswith('"'):
            s = raw[1:-1].encode("utf-8").decode("unicode_escape")
        elif raw.startswith("`"):
            s = raw[1:-1]
        else:
            continue
        bc, err = macro.compile(s)
        assert err is None, f"Catalog snippet failed compilation: {s!r} -> {err}"
        assert bc is not None and len(bc) > 0


def test_pixel_assist_snippets_compile(macro):
    """Verifies that point and region snippets generated by Pixel Assist compile cleanly."""
    # Point snippet
    pt_code = (
        "\\use{img}\\\n"
        "\\call{img.snap}{100, 200, 1, 1}\\set{px}{$ret}\\\n"
        "\\call{img.at}{$px}{0, 0}\\\n"
        "\\if{ {$ret, =, 0xFF0000} }{\\# color matched\n"
        "}{\\# color mismatched\n"
        "}"
    )
    bc_pt, err_pt = macro.compile(pt_code)
    assert err_pt is None, f"Point snippet failed compilation: {err_pt}"
    assert bc_pt is not None and len(bc_pt) > 0

    # Region snippet (small with pixelrect)
    reg_code = (
        "\\use{img}\\\n"
        "\\pixelrect{ref}{\n"
        "  \\row{0xFF0000, 0x00FF00}\n"
        "}\\\n"
        "\\call{img.snap}{10, 20, 2, 1}\\set{cur}{$ret}\\\n"
        "\\call{img.diff}{$ref}{$cur}{16}\\\n"
        "\\if{ {$ret, =, 0} }{\\# identical\n"
        "}{\\# changed\n"
        "}"
    )
    bc_reg, err_reg = macro.compile(reg_code)
    assert err_reg is None, f"Region snippet failed compilation: {err_reg}"
    assert bc_reg is not None and len(bc_reg) > 0


def test_all_catalog_call_signatures(macro):
    r"""Ensures that every \call in catalog.ts targets a registered extension API
    and matches its exact signature."""
    catalog_path = Path("web/src/modules/catalog.ts")
    content = catalog_path.read_text(encoding="utf-8")

    calls = re.findall(r"\\call\{([a-zA-Z][a-zA-Z0-9_.]*)\}", content)
    assert len(calls) > 0

    for target in set(calls):
        ns, _, fn = target.partition(".")
        assert macro.runtime.has_namespace(ns), f"Namespace {ns} not registered"
        sig = macro.runtime.get_signature(ns, fn)
        assert sig is not None, f"Unknown fn {fn} in namespace {ns}"


def test_no_obsolete_dsl_v3_syntax_in_frontend():
    """Ensures obsolete \\rect and \\ifnum syntax are completely eliminated from frontend source."""
    web_src = Path("web/src")
    for f in web_src.rglob("*.ts"):
        text = f.read_text(encoding="utf-8")
        assert r"\rect{" not in text, f"Found obsolete \\rect in {f}"
        assert r"\ifnum" not in text, f"Found obsolete \\ifnum in {f}"

    index_html = Path("web/index.html").read_text(encoding="utf-8")
    assert r"\ifnum" not in index_html, "Found obsolete \\ifnum in web/index.html"
